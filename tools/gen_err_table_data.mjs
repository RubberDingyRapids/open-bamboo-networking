// gen_err_table_data.mjs - deterministic generator for src/err_table_data.cpp.
//
// Reads the SHA-256-pinned PandaSpy HMS asset (en.json) and emits two
// key-sorted {key, message} tables (hms + print_error) inside
// namespace obn::err::data. Node built-ins only - no packages, no network
// (the asset is fetched separately and pinned by hash before this runs).
//
// Determinism contract: same input bytes -> byte-identical output. Keys are
// sorted lexicographically (byte order for these ASCII hex keys); messages
// are emitted with a fixed escaping rule (see cEscape below) so the source
// file stays pure ASCII and never contains a run of escapes that could
// merge at parse time.
//
// Usage (the regeneration command recorded in the generated header):
//   node tools/gen_err_table_data.mjs "<path-to>/en.json" src/err_table_data.cpp

